import {mkdir,readFile,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
import {root,python} from '../src/runner.js';
import {exec,normalizeVoice,readWords,srt} from '../src/media.js';
const out=path.resolve(process.argv[2]??path.join(root,'examples/assets/reel'));
await mkdir(path.dirname(out),{recursive:true});await mkdir(out);
const voice=path.join(out,'voice.wav'),asr=path.join(out,'transcript-asr.json');
const pop=process.argv.includes('--pop');
const generated=await exec(python,[path.join(root,'scripts/prepare-reel-showcase.py'),'--out',out,...(pop?['--style','pop','--project','examples/pop-showcase.json','--script','examples/assets/pop-narration-script.json']:[])],{maxBuffer:3e6});console.log(generated.stdout);
await normalizeVoice(path.join(out,'voice-raw.wav'),voice);
await exec(python,[path.join(root,'python/local_media.py'),'transcribe','--input',voice,'--output',asr,'--model','base','--language','en'],{maxBuffer:3e6});
const words=await readWords(asr);
const timing=JSON.parse(await readFile(path.join(out,'voice-timing.json'),'utf8'));
const script=timing.flatMap((s:any)=>s.text.split(/\s+/).map((text:string)=>({text,start:s.start,end:s.end})));
console.log('ASR:',words.map(w=>w.text).join(' '));console.log('Words:',words.length,'script:',script.length);
if(words.length!==script.length)throw new Error('ASR count differs: review measured alignment before writing final transcript');
const corrected=words.map((w,i)=>({text:script[i].text,start:Math.max(w.start,script[i].start),end:Math.min(w.end,script[i].end)}));
if(corrected.some(w=>w.end<=w.start))throw new Error('ASR window differs: review measured alignment');
await writeFile(path.join(out,'transcript.json'),JSON.stringify({version:1,timing:'ASR; scripted spelling/punctuation; constrained to synthesis windows',words:corrected},null,2));
await writeFile(path.join(out,'captions.srt'),srt(corrected));
await rm(path.join(out,'voice-raw.wav'));
console.log('Prepared:',out);
